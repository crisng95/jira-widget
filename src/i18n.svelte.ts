const dicts: Record<Lang, Record<string, string>> = { vi, en };

export function t(key: string, params?: Record<string, string | number>): string {
  let s = dicts[state.lang][key] ?? vi[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Dem nguoc: "2d 4h" / "9h 42m" / "12m"; qua han thi bo tien to theo ngon ngu. */
export function fmtCountdown(secs: number | null): string {
  if (secs === null) return "—";
  const past = secs < 0;
  let s = Math.abs(secs);
  const d = Math.floor(s / 86400);
  s -= d * 86400;
  const h = Math.floor(s / 3600);
  s -= h * 3600;
  const m = Math.floor(s / 60);
  const body = d > 0 ? `${d}d ${h}h` : h > 0 ? `${h}h ${m}m` : `${m}m`;
  return past ? t("overdue", { t: body }) : body;
}

export function fmtClock(iso: string | null): string {
  if (!iso) return "—";
  const d = new Date(iso);
  return d.toLocaleTimeString(state.lang === "vi" ? "vi-VN" : "en-GB", {
    hour: "2-digit",
    minute: "2-digit",
  });
}
