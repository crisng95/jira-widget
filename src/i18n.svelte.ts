// i18n nhe cho ca ba man (panel, Cai dat, wizard). Hai ngon ngu du: vi/en.
// Cac ngon ngu khac hien trong wizard o dang "nhap" va bi khoa.
//
// `lang` la $state cap module — moi bieu thuc template goi t() se tu render
// lai khi doi ngon ngu, khong can reload webview.

export type Lang = "vi" | "en";

const state = $state({ lang: "vi" as Lang });

export function getLang(): Lang {
  return state.lang;
}

export function setLang(l: string): void {
  state.lang = l === "en" ? "en" : "vi";
}

/** Ngon ngu doan tu he dieu hanh — dung lam mac dinh trong wizard. */
export function osLang(): Lang {
  return (navigator.language || "").toLowerCase().startsWith("vi") ? "vi" : "en";
}

